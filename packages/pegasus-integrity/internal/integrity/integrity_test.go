func TestCheckIntegrityComputationFailureRendersNoneSentinel(t *testing.T) {
	// Matches Python: generate_sha256() failing doesn't short-circuit the
	// comparison — current_sha256 stays Python's None, which is compared
	// (and, if --print-timings, rendered in YAML) as the literal text
	// "None", not treated as a distinct error path.
	meta := []MetaEntry{{ID: "missing", Attributes: map[string]string{"checksum.value": helloWorldSHA256}}}
	stats := &Stats{}
	result := CheckIntegrity("/does/not/exist", "missing", meta, stats)
	if result.Success {
		t.Fatal("expected failure")
	}
	if result.SHA256Valid || result.SHA256 != "None" {
		t.Fatalf("expected None sentinel, got %+v", result)
	}
	if stats.Failed != 1 {
		t.Fatalf("expected the failure to still be counted, got %+v", stats)
	}
}
