func TestGenerateFullstatYAML(t *testing.T) {
	dir := t.TempDir()
	path := writeFile(t, dir, "data.1", "Hello World\n")

	yaml, err := GenerateFullstatYAML("data.1", path)
	if err != nil {
		t.Fatal(err)
	}
	for _, want := range []string{
		`"data.1":`,
		"comment: entry generated by pegasus-integrity",
		"size: 12",
		"output: True",
		"sha256: " + helloWorldSHA256,
	} {
		if !strings.Contains(yaml, want) {
			t.Errorf("missing %q in:\n%s", want, yaml)
		}
	}
}

