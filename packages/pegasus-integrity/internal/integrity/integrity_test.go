func TestReadMetaData(t *testing.T) {
	entries, err := ReadMetaData("../../testdata/data.meta")
	if err != nil {
		t.Fatal(err)
	}
	if len(entries) != 2 {
		t.Fatalf("got %d entries, want 2", len(entries))
	}
	if entries[0].ID != "data.1" {
		t.Fatalf("got id %s", entries[0].ID)
	}
	if v, ok := entries[0].ChecksumValue(); !ok || v != helloWorldSHA256 {
		t.Fatalf("got checksum %s ok=%v", v, ok)
	}
}

func TestReadMetaDataEmptyFile(t *testing.T) {
	dir := t.TempDir()
	path := writeFile(t, dir, "empty.meta", "[]")
	// "[]" is 2 bytes, matching the Python original's `size <= 2` skip.
	entries, err := ReadMetaData(path)
	if err != nil {
		t.Fatal(err)
	}
	if entries != nil {
		t.Fatalf("expected no entries for a <=2 byte file, got %v", entries)
	}
}

func TestCheckIntegritySuccess(t *testing.T) {
	dir := t.TempDir()
	path := writeFile(t, dir, "data.1", "Hello World\n")
	meta := []MetaEntry{{ID: "data.1", Attributes: map[string]string{"checksum.value": helloWorldSHA256}}}

	stats := &Stats{}
	result := CheckIntegrity(path, "data.1", meta, stats)
	if !result.Success || result.NoMetaEntry {
		t.Fatalf("expected success, got %+v", result)
	}
	if stats.Succeeded != 1 || stats.Failed != 0 {
		t.Fatalf("got stats %+v", stats)
	}
}

