func TestCheckIntegrityNoMetaEntry(t *testing.T) {
	dir := t.TempDir()
	path := writeFile(t, dir, "data.1", "Hello World\n")

	stats := &Stats{}
	result := CheckIntegrity(path, "unknown-lfn", nil, stats)
	if !result.NoMetaEntry {
		t.Fatalf("expected NoMetaEntry, got %+v", result)
	}
	// Matches Python: the early-return path touches no counters at all.
	if stats.Succeeded != 0 || stats.Failed != 0 || stats.Duration != 0 {
		t.Fatalf("expected untouched stats, got %+v", stats)
	}
}

